import fs from 'node:fs';
import type {SidebarsConfig} from '@docusaurus/plugin-content-docs';

// The API reference pages and their sidebars are generated from openapi/*.yaml by `npm run gen-api`.
function generated(name: string) {
  const path = `./docs/api/${name}/sidebar.ts`;
  return fs.existsSync(path) ? require(path).default : [];
}

const sidebars: SidebarsConfig = {
  docs: [
    'intro',
    {type: 'category', label: 'Getting started', collapsed: false, items: [{type: 'autogenerated', dirName: 'start'}]},
    {type: 'category', label: 'Guides', collapsed: false, items: [{type: 'autogenerated', dirName: 'guides'}]},
  ],
  api: [
    'api/index',
    {type: 'category', label: 'Agent API', collapsed: false, items: generated('agent')},
    {type: 'category', label: 'Studio API', items: generated('studio')},
  ],
  library: [{type: 'autogenerated', dirName: 'library'}],
};

export default sidebars;
